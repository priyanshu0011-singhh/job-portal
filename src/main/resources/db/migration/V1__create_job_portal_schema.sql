CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE users (
    user_id VARCHAR(255) PRIMARY KEY,
    user_name VARCHAR(255) NOT NULL,
    user_email VARCHAR(255) NOT NULL UNIQUE,
    user_passwords VARCHAR(255) NOT NULL,
    user_contact_numbers VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6)
);

CREATE TABLE jobs (
    job_id VARCHAR(255) PRIMARY KEY,
    application_dead_line VARCHAR(255),
    company VARCHAR(255),
    created_at TIMESTAMP(6),
    job_description VARCHAR(1000),
    experience_level VARCHAR(255),
    industry VARCHAR(255),
    is_active BOOLEAN NOT NULL,
    job_type VARCHAR(255),
    location VARCHAR(255),
    job_posted_date VARCHAR(255),
    salary DOUBLE PRECISION NOT NULL,
    skills VARCHAR(255),
    job_title VARCHAR(255),
    posted_by_user VARCHAR(255),
    CONSTRAINT fk_jobs_posted_by_user FOREIGN KEY (posted_by_user) REFERENCES users (user_id)
);

CREATE TABLE applications (
    id VARCHAR(255) PRIMARY KEY,
    application_date VARCHAR(255),
    application_status VARCHAR(255),
    resume_link VARCHAR(255),
    applicant_id VARCHAR(255),
    job_id VARCHAR(255),
    CONSTRAINT fk_applications_applicant FOREIGN KEY (applicant_id) REFERENCES users (user_id),
    CONSTRAINT fk_applications_job FOREIGN KEY (job_id) REFERENCES jobs (job_id)
);

CREATE TABLE user_roles (
    user_id VARCHAR(255) NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (id)
);